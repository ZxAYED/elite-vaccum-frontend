type ProductSeed = Omit<
  Product,
  "status" | "imageAlt" | "highlights" | "specifications" | "shippingNotes"
> & {
  imageAlt?: string;
  availability?: ProductAvailability;
};

const defaultHighlights = [
  "Verified compatibility guidance from the Elite service team.",
  "Clean fulfillment tracking with dashboard-visible order history.",
  "Built for dependable central vacuum performance.",
];

function createProduct(seed: ProductSeed): Product {
  return {
    status: "active",
    availability: "in-stock",
    imageAlt: `${seed.name} for central vacuum systems`,
    highlights: defaultHighlights,
    specifications: [
      { label: "Category", value: seed.eyebrow ?? "Store item" },
      { label: "Support", value: "Elite compatibility review available" },
      { label: "Fulfillment", value: "Tracked store checkout" },
    ],
    shippingNotes: [
      "Usually ships within 2 business days.",
      "Tracking is emailed as soon as the item leaves the warehouse.",
    ],
    ...seed,
  };
}

